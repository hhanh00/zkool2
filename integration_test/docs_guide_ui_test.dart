/// Docs screenshots: the Guide pages of the docs site.
///
/// Not a test of the app but a scripted walkthrough that
/// `tests/tests/test_docs_guide_ui.py` drives on regtest: the empty account
/// manager, a new account and its seed phrase, a restored account with its
/// advanced options, the account list, the account page before and after
/// funds arrive, the receive page, a payment through the extra options and
/// the transaction plan, and a multi-recipient queue. Every shot is named
/// after the image it replaces under `docs/guide/images` in the docs site,
/// with the annotations the page text refers to. See
/// `docs_shots_support.dart` for how the shots are recorded.
library;

import 'dart:async';

import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:zkool/main.dart';
import 'package:zkool/pages/account.dart';
import 'package:zkool/pages/tx.dart';
import 'package:zkool/router.dart';
import 'package:zkool/src/rust/api/account.dart';
import 'package:zkool/store.dart';
import 'package:zkool/utils.dart';
import 'package:zkool/widgets/theme.dart';

import 'docs_shots_support.dart';
import 'support.dart';

const _main = "Main Account";
const _old = "Old Account";
// The seed phrase the docs have always shown: generated by the app once,
// never funded.
const _oldSeed = "control scan mix boat vendor airport universe note ignore north resemble planet "
    "news gadget sport addict route betray check fiction speak violin token entry";
const _oldBirth = "200";
const _amount = "0.05";
const _memo = "Thanks for the docs!";
const _seedDialog = "SEED PHRASE - SAVE IT OR YOU CAN LOSE YOUR FUNDS";
const _newAccountHint = "Create a new wallet or restore an existing one";
const _scanPrompt = "Scan for alternative transparent addresses?";
const _queueTooltip = "Queue this recipient to create a multi send";
// Long enough for a toast, such as the synchronizer's, to have gone.
const toastGone = Duration(seconds: 6);

void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();
  // ignore: avoid_print
  debugPrint = (String? message, {int? wrapWidth}) => print(message ?? "");

  testWidgets("Docs: guide screenshots", (tester) async {
    final docsDir = await appDocumentsDir();
    final rendezvous = Rendezvous.fromEnvironment(docsDir);
    expect(rendezvous.dir.existsSync(), isTrue,
        reason: "rendezvous dir ${rendezvous.dir.path} missing — "
            "start this from test_docs_guide_ui.py",);

    final config = rendezvous.readConfig();
    final dbPath = config["db_path"] as String;
    final destination = config["destination"] as String;
    final transparent = config["transparent"] as String;
    final sapling = config["sapling"] as String;
    final fund = config["fund"] as String;
    expect(dbPath, contains("regtest"));

    final prefs = SharedPreferencesAsync();
    final savedPrefs = await SavedPrefs.forceTestValues(prefs, defaultTheme: true);
    final shots = Shots(tester, docsDir, config);

    Future<void> waitForNewAccountPage() => pumpUntil(
          tester,
          () => find.text(_newAccountHint).evaluate().isNotEmpty,
          timeout: shortTimeout,
          what: "the new account page",
        );

    // A badge just right of the widget [finder] matches, outside it.
    Annot besides(Finder finder, int n) => shots.badgeAt(shots.rectOf(finder).centerRight + const Offset(26, 0), n);

    // Finders for every widget of [type] on screen, one per instance.
    Iterable<Finder> each(Type type) => find.byType(type).evaluate().map((e) => find.byWidget(e.widget));

    try {
      await tester.runAsync(() async {
        await openTestWallet(
          dbPath: dbPath,
          lwd: config["lwd"] as String,
          docsDir: docsDir.path,
        );
      });

      final appRouter = router(true, false, initialLocation: "/accounts");
      await tester.pumpWidget(RepaintBoundary(key: shots.boundary, child: ZkoolApp(router: appRouter)));
      await tester.pump(const Duration(seconds: 1));
      final container = ProviderScope.containerOf(tester.element(find.byType(MaterialApp)));
      await primeProviders(tester, container);
      await waitForAccountList(tester);
      // The height button reads N/A until the chain is asked, which a tap on
      // it does along with the market price; ask for the height alone.
      await tester.runAsync(() => container.read(currentHeightProvider.notifier).fetch(force: true));
      await pumpUntil(tester, () => find.text("Height: N/A").evaluate().isEmpty,
          timeout: shortTimeout, what: "the chain height",);
      await shots.take("guide/images/01.account_mgr");

      // ── New account ──────────────────────────────────────────────────────
      await tester.tap(find.widgetWithText(ElevatedButton, "New Account"));
      await waitForNewAccountPage();
      await shots.take("guide/images/02.new_account", annots: () => [
        shots.badge(fieldNamed("name"), 1),
        besides(find.byIcon(Icons.edit), 2),
        shots.badgeAt(shots.rectOf(find.byTooltip("Save")).bottomCenter + const Offset(0, 22), 3),
      ]);
      await tester.enterText(fieldNamed("name"), _main);
      await tester.pump();
      await tapTooltip(tester, "Save");
      await pumpUntil(tester, () => find.text(_seedDialog).evaluate().isNotEmpty && find.text("Ok").evaluate().isNotEmpty,
          timeout: shortTimeout, what: "the seed phrase dialog",);
      await shots.take("guide/images/03.seed");
      await tester.tap(find.text("Ok").last);
      await waitForAccountView(tester, _main);
      final a = (await tester.runAsync(() => accountIds()))![_main]!;
      await shots.take("guide/images/04.first_account");

      // ── Restore ──────────────────────────────────────────────────────────
      unawaited(appRouter.push("/account/new"));
      await waitForNewAccountPage();
      await tester.enterText(fieldNamed("name"), _old);
      await tester.pump();
      await tester.tap(switchNamed("restore"));
      await pumpUntil(tester, () => fieldNamed("key").evaluate().isNotEmpty,
          timeout: shortTimeout, what: "the key field",);
      await shots.take("guide/images/05.restore_1", annots: () => [
        shots.badge(fieldNamed("name"), 1),
        besides(find.byIcon(Icons.edit), 2),
        besides(find.text("Restore Account?"), 3),
      ]);
      await tester.enterText(fieldNamed("key"), _oldSeed);
      await tester.pump();
      await tester.enterText(fieldNamed("birth"), _oldBirth);
      await tester.pump();
      await tester.tap(switchNamed("advanced"));
      await pumpUntil(tester, () => fieldNamed("aindex").evaluate().isNotEmpty,
          timeout: shortTimeout, what: "the advanced options of a seed phrase",);
      await tester.ensureVisible(fieldNamed("aindex").first);
      await tester.pump();
      await shots.take("guide/images/06.restore_seed", annots: () => [
        shots.badge(fieldNamed("passphrase"), 1),
        shots.badge(fieldNamed("aindex"), 2),
      ]);
      await tapTooltip(tester, "Save");
      // A restored account with a transparent pool is offered a scan for
      // the addresses a rotating wallet may have used.
      await pumpUntil(tester, () => find.text(_scanPrompt).evaluate().isNotEmpty && find.text("Close").evaluate().isNotEmpty,
          timeout: shortTimeout, what: "the transparent address scan prompt",);
      await shots.take("guide/images/17.scan_prompt");
      await tester.tap(find.text("Close").last);
      // Then whether to synchronize it right away; the docs say to restore
      // every account first.
      await answerDialog(tester, "Account imported successfully. Would you like to synchronize it now?", "Cancel");
      await waitForAccountView(tester, _old);

      // ── Account list ─────────────────────────────────────────────────────
      appRouter.go("/accounts");
      await waitForAccountList(tester);
      await pumpUntil(tester, () => find.byType(SmallProgressWidget).evaluate().length >= 2,
          timeout: shortTimeout, what: "both account rows",);
      // One box per account height, around the text itself: the widget's
      // box is larger than what it shows, and a single box around both
      // would cut across the second account's name.
      await shots.take("guide/images/07.sync", annots: () => [
        for (final height in each(SmallProgressWidget)) shots.textBox(height),
        shots.box(find.byTooltip("Synchronize all enabled accounts or the accounts currently selected"), color: "green"),
      ]);

      // ── Account page, still empty ────────────────────────────────────────
      appRouter.go(accountRoute("/", a));
      await waitForAccountView(tester, _main);
      await pumpUntil(tester, () => find.byType(BalanceWidget).evaluate().isNotEmpty,
          timeout: shortTimeout, what: "the pool balances",);
      await shots.take("guide/images/08.account", annots: () => [
        shots.box(find.byTooltip("Balance across all pools")),
        shots.box(find.byType(BalanceWidget), color: "green"),
        shots.boxAround([
          find.widgetWithText(TextField, "Search transactions (memo, contact, txid)"),
          find.textContaining("Transaction History"),
        ], color: "blue"),
      ]);

      // ── Receive ──────────────────────────────────────────────────────────
      await tapTooltip(tester, "Show the account receiving addresses");
      final addresses = (await tester.runAsync(
        () => getAddresses(uaPools: 7, account: a, c: coinContext.coin),
      ))!;
      await pumpUntil(tester, () => find.text("Receive Funds").evaluate().isNotEmpty && copyableWith(addresses.ua!).evaluate().isNotEmpty,
          timeout: shortTimeout, what: "the receive page with the unified address",);
      rendezvous.publish("a_ua", addresses.ua!);
      await shots.take("guide/images/10.addresses", annots: () => [
        shots.box(find.byTooltip("Generate a new set of addresses (transparent/sapling and orchard). Previous addresses can still receive funds")),
      ]);

      // ── Funded ───────────────────────────────────────────────────────────
      await tester.pageBack();
      await waitForAccountView(tester, _main);
      await waitForBalance(tester, a, atLeast: zecToZat(fund), what: "the funding to arrive");
      await waitForSync(tester, a);
      // The sync's "completed" toast has to go first.
      await shots.take("guide/images/11.send_1", settle: toastGone, annots: () => [
        shots.box(find.byTooltip("Send funds to one or many addresses")),
      ]);

      // ── Send ─────────────────────────────────────────────────────────────
      await tapTooltip(tester, "Send funds to one or many addresses");
      await pumpUntil(tester, () => fieldNamed("address").evaluate().isNotEmpty,
          timeout: shortTimeout, what: "the send page",);
      await enterRecipient(tester, destination, _amount, memo: _memo);
      await shots.take("guide/images/12.send_2");
      await tapTooltip(tester, "Send transaction (including queued recipients)");
      await pumpUntil(tester, () => find.text("Extra Options").evaluate().isNotEmpty,
          timeout: shortTimeout, what: "the send options page",);
      await shots.take("guide/images/13.send_3", annots: () => [
        besides(find.text("Source Pools"), 1),
        besides(find.text("Recipient Pays Fee"), 2),
        besides(find.text("Category"), 3),
      ]);
      await tapTooltip(tester, "Send (Summary and Confirmation)");
      await pumpUntil(tester, () => find.byType(TxPage).evaluate().isNotEmpty && find.textContaining("Fee: ").evaluate().isNotEmpty,
          timeout: const Duration(minutes: 2), what: "the transaction summary",);
      await shots.take("guide/images/14.tx_plan", annots: () => [
        shots.round(find.textContaining("Fee: ")),
        shots.boxAround(each(ListTile)),
      ]);
      await tapTooltip(tester, "Confirm, broadcast transaction");
      await answerDialog(tester, "Are you sure you want to send this transaction?", "Ok");
      String txLine = "";
      await pumpUntil(tester, () {
        final found = find.byWidgetPredicate((w) => w is CopyableText && w.text.startsWith("Transaction ID: ")).evaluate();
        if (found.isEmpty) return false;
        txLine = (found.first.widget as CopyableText).text;
        return true;
      }, timeout: const Duration(minutes: 3), what: "the transaction id",);
      rendezvous.publish("txid", txLine.substring("Transaction ID: ".length).trim());
      await pumpUntil(tester, () => rendezvous.readOrchestrator()?["mined"] == true,
          timeout: chainTimeout, what: "the orchestrator to mine the payment",);

      // ── History ──────────────────────────────────────────────────────────
      appRouter.go(accountRoute("/", a));
      await waitForAccountView(tester, _main);
      await waitForSync(tester, a);
      await tapTab(tester, "Transactions");
      await pumpUntil(tester, () => find.text("Sent").evaluate().isNotEmpty,
          timeout: shortTimeout, what: "the outgoing transaction in the history",);
      // The badges sit on the divider under the first row: its type, date
      // and amount columns.
      final row = shots.rectOf(find.byType(TransactionTile));
      await shots.take("guide/images/09.tx_history", settle: toastGone, annots: () => [
        shots.badgeAt(Offset(row.left + row.width * 0.2, row.bottom), 1),
        shots.badgeAt(Offset(row.left + row.width * 0.5, row.bottom), 2),
        shots.badgeAt(Offset(row.left + row.width * 0.85, row.bottom), 3),
      ]);

      // ── Multi recipients ─────────────────────────────────────────────────
      await tapTooltip(tester, "Send funds to one or many addresses");
      await pumpUntil(tester, () => fieldNamed("address").evaluate().isNotEmpty,
          timeout: shortTimeout, what: "the send page again",);
      await enterRecipient(tester, transparent, "0.1");
      await tapTooltip(tester, _queueTooltip);
      await enterRecipient(tester, sapling, "0.2");
      await tapTooltip(tester, _queueTooltip);
      await pumpUntil(tester, () => find.byIcon(Icons.delete).evaluate().length >= 2,
          timeout: shortTimeout, what: "the two queued recipients",);
      await shots.take("guide/images/16.multi", annots: () => [
        shots.boxAround(each(ListTile)),
      ]);

      shots.finish();
      rendezvous.publish("done", "true");
      await pumpFor(tester, const Duration(seconds: 1));
    } finally {
      await savedPrefs.restore(prefs);
    }
  }, timeout: const Timeout(Duration(minutes: 20)));
}
